import fs from 'fs';
import path from 'path';

// ─── GENERATE REDIRECTS SCRIPT ───
// 1. Reads redirects.json (single source of truth for all redirect rules).
// 2. Generates public/_redirects:
//    - Strictly respects Cloudflare Pages' 2,000 static line limit.
//    - Prioritizes SEO trailing-slash fixes, Stanley Cup & high-impression pages,
//      and all English appliance redirects.
//    - Normalizes targets to end with '/' to prevent 301 -> 308 redirect chains.
//    - Enforces hard build-time assertion <= 2,000 lines.
// 3. Generates functions/_redirects-map.js:
//    - Request-time edge fallback map containing 100% of all redirect rules (all languages & verticals).
//    - Used by functions/_middleware.js so no redirect ever silently 404s, even with 10k+ pages.

const redirectsPath = path.resolve('redirects.json');
const publicRedirectsPath = path.resolve('public', '_redirects');
const functionsMapPath = path.resolve('functions', '_redirects-map.js');

const rawRedirects = JSON.parse(fs.readFileSync(redirectsPath, 'utf8'));

// ─── Helper: Normalize Paths ───
function normalizeSource(p) {
  return p.length > 1 ? p.replace(/\/+$/, '') : p;
}

function normalizeTarget(p) {
  return p.endsWith('/') ? p : `${p}/`;
}

// ─── Step 1: Generate functions/_redirects-map.js (Full 100% Database) ───
const uniqueEntries = new Map();
for (const rule of rawRedirects) {
  const src = normalizeSource(rule.source);
  const tgt = normalizeTarget(rule.target);
  uniqueEntries.set(src, tgt);
}

let mapFileContent = '// Auto-generated by scripts/generate-redirects.js\n';
mapFileContent += '// Full redirect lookup database for Cloudflare Pages Functions edge middleware.\n';
mapFileContent += '// Provides O(1) in-memory resolution for all redirects, bypassing static parser limits.\n\n';
mapFileContent += 'export const redirectsMap = new Map([\n';

for (const [src, tgt] of uniqueEntries) {
  mapFileContent += `  [${JSON.stringify(src)}, ${JSON.stringify(tgt)}],\n`;
}
mapFileContent += ']);\n';

fs.writeFileSync(functionsMapPath, mapFileContent, 'utf8');
console.log(`✅ [Edge Middleware] Generated functions/_redirects-map.js with ${uniqueEntries.size} entries.`);

// ─── Step 2: Generate public/_redirects (Static CDN Edge Fast-Path) ───
// Cloudflare Pages Limit: Max 2,000 static lines. Lines past 2,000 are silently ignored.
// Target budget: <= 1,980 lines to allow safe buffer for comments and headers.
const MAX_STATIC_RULES = 1980;

const seoRedirects = [
  '/how-long/chicken-in-fridge /how-long/chicken-in-fridge/ 301',
  '/dishwasher /dishwasher/ 301',
  '/dishwasher/cast-iron-skillet /dishwasher/cast-iron-skillet/ 301',
  '/dryer/crocs /dryer/crocs/ 301',
  '/microwave/aluminum-foil /microwave/aluminum-foil/ 301',
  '/material/fabric /material/fabric/ 301',
  '/material/metal /material/metal/ 301',
  '/how-long /how-long/ 301',
  '/microwave /microwave/ 301',
  '/oven /oven/ 301',
];

// Sort and prioritize rules for public/_redirects:
// Priority 1: Stanley Cup Tumbler & high-impression pages
// Priority 2: Refrigerator rules (formerly broken past line 2,000)
// Priority 3: Other English appliance rules (Airfryer, Dryer, Freezer, Microwave, Oven, etc.)
// Priority 4: ES (Spanish) rules
// Priority 5: PT (Portuguese) rules

const stanleyRules = [];
const fridgeRules = [];
const otherEnRules = [];
const esRules = [];
const ptRules = [];

for (const [src, tgt] of uniqueEntries) {
  const item = { source: src, target: tgt };
  if (src.includes('stanley-cup')) {
    stanleyRules.push(item);
  } else if (src.startsWith('/refrigerator/')) {
    fridgeRules.push(item);
  } else if (src.startsWith('/es/')) {
    esRules.push(item);
  } else if (src.startsWith('/pt/')) {
    ptRules.push(item);
  } else {
    otherEnRules.push(item);
  }
}

const prioritizedQueue = [
  ...stanleyRules,
  ...fridgeRules,
  ...otherEnRules,
  ...esRules,
  ...ptRules,
];

let staticOutput = '# Auto-generated by scripts/generate-redirects.js\n';
staticOutput += '# Do not edit this file directly. Edit redirects.json instead.\n';
staticOutput += `# Cloudflare Pages Static Limit: 2,000 lines. Budget: ${MAX_STATIC_RULES} rules.\n`;
staticOutput += '# Rules beyond the budget are dynamically handled by functions/_middleware.js.\n\n';

staticOutput += '# === SEO: Trailing-slash 301 redirects ===\n';
for (const seoRule of seoRedirects) {
  staticOutput += `${seoRule}\n`;
}
staticOutput += '\n# === High-Priority Appliance Redirects (Direct 301 to Canonical Slash) ===\n';

let currentLineCount = seoRedirects.length;
let rulesAddedToStatic = 0;

for (const rule of prioritizedQueue) {
  // Each rule adds 2 lines (no-slash and with-slash)
  if (currentLineCount + 2 > MAX_STATIC_RULES) {
    break;
  }
  staticOutput += `${rule.source} ${rule.target} 301\n`;
  staticOutput += `${rule.source}/ ${rule.target} 301\n`;
  currentLineCount += 2;
  rulesAddedToStatic++;
}

fs.writeFileSync(publicRedirectsPath, staticOutput, 'utf8');

// ─── Step 3: Hard Build-Time Assertion ───
const generatedLines = staticOutput
  .split('\n')
  .map(l => l.trim())
  .filter(l => l.length > 0 && !l.startsWith('#'));

console.log(`✅ [Static _redirects] Generated ${generatedLines.length} static redirect lines (${rulesAddedToStatic} entries + ${seoRedirects.length} SEO rules).`);
console.log(`📊 [Budget Status] ${generatedLines.length} / 2,000 lines used (${2000 - generatedLines.length} lines headroom).`);

if (generatedLines.length > 2000) {
  throw new Error(`🚨 FATAL: public/_redirects has ${generatedLines.length} lines, exceeding Cloudflare's 2,000 limit! Build aborted.`);
}
