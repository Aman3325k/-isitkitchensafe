import fs from 'fs';
import path from 'path';

// This script reads redirects.json and generates public/_redirects
// ensuring every rule has an exact match and a trailing slash variant.

const redirectsPath = path.resolve('redirects.json');
const outputPath = path.resolve('public', '_redirects');

const redirects = JSON.parse(fs.readFileSync(redirectsPath, 'utf8'));

// ─── SEO-critical rules: must come first (Cloudflare Pages first-match wins) ───

// 1. www → non-www canonical redirect (301)
//    Prevents Google crawling www.isitkitchensafe.com as a separate site.
//    Fixes the www/non-www split that was inflating "Page with redirect" count.
const wwwRedirects = `# === SEO: www → non-www canonical redirect ===
https://www.isitkitchensafe.com/* https://isitkitchensafe.com/:splat 301

# === SEO: Trailing-slash 301 redirects ===
# Astro's trailingSlash: 'always' emits HTTP 308 for no-slash → with-slash redirects.
# Google Search Console flags 308s as "Redirect error". These explicit 301 rules
# fire first (Cloudflare Pages is first-match) and prevent the 308 from being served.
# Source: GSC Indexing > Pages > "Redirect error" (10 URLs, confirmed Sep 15 2026).
/how-long/chicken-in-fridge /how-long/chicken-in-fridge/ 301
/dishwasher /dishwasher/ 301
/dishwasher/cast-iron-skillet /dishwasher/cast-iron-skillet/ 301
/dryer/crocs /dryer/crocs/ 301
/microwave/aluminum-foil /microwave/aluminum-foil/ 301
/material/fabric /material/fabric/ 301
/material/metal /material/metal/ 301
/how-long /how-long/ 301
/microwave /microwave/ 301
/oven /oven/ 301

`;

let outputContent = '# Auto-generated by scripts/generate-redirects.js\n';
outputContent += '# Do not edit this file directly. Edit redirects.json instead.\n\n';
outputContent += wwwRedirects;

for (const rule of redirects) {
  const { source, target } = rule;
  
  // Rule without trailing slash
  outputContent += `${source} ${target} 301\n`;
  
  // Rule with trailing slash
  if (!source.endsWith('/')) {
    outputContent += `${source}/ ${target} 301\n`;
  }
}

fs.writeFileSync(outputPath, outputContent, 'utf8');
console.log(`Generated ${redirects.length * 2} redirect rules to public/_redirects (+ SEO prefix rules)`);
